// Regression test for the captions-disappear bug in 0.1.3: Media3 1.4+ parses
// subtitles during extraction and its text renderer refuses legacy
// `text/vtt` samples ("legacy decoding is disabled"), which killed playback
// and made the player drop the captions. Side-loaded tracks must run through
// SubtitleExtractor, which turns WebVTT into `application/x-media3-cues`
// samples. This exercises the exact wiring IndioMediaSourceFactory now uses
// for every caption track. Robolectric is required because Media3's WebVTT
// parser genuinely uses android.text (TextUtils, SpannableStringBuilder).
@RunWith(RobolectricTestRunner::class)
class SubtitlePipelineTest {

    private val http: OkHttpClient = OkHttpClient.Builder()
        .connectTimeout(20, TimeUnit.SECONDS)
        .readTimeout(30, TimeUnit.SECONDS)
        .build()

    @Test
    fun webVttBecomesMedia3CueSamples() {
        val webVtt = """
            WEBVTT
            Kind: captions
            Language: en

            00:00:01.000 --> 00:00:03.000 align:start position:0%
            <c>We're no strangers to love</c>

            00:00:03.500 --> 00:00:05.000
            You know the rules and so do I
        """.trimIndent()

        val result = extractCueSamples(webVtt.toByteArray(Charsets.UTF_8))

        assertEquals(MimeTypes.APPLICATION_MEDIA3_CUES, result.mimeType)
        assertTrue("cue samples expected, got ${result.sampleCount}", result.sampleCount > 0)
        assertTrue("sample payload must not be empty", result.firstSampleSize > 0)
    }

    // The real YouTube payload (cue settings, entity references, styling tags)
    // must survive the same pipeline, so this is the live half of the
    // regression guard.
    @Test
    fun liveYouTubeWebVttBecomesMedia3CueSamples() = runBlocking {
        StreamResolver.init(http)
        val resolver = StreamResolver(http)
        val qualities = resolver.qualities("dQw4w9WgXcQ")
        val manual = qualities.subtitles.firstOrNull { !it.autoGenerated }
        assertNotNull("manual captions expected", manual)

        val request = Request.Builder()
            .url(manual!!.url)
            .header(
                "User-Agent",
                "Mozilla/5.0 (Linux; Android 14) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/122.0 Mobile Safari/537.36",
            )
            .build()
        val body = http.newCall(request).execute().use { it.body?.string().orEmpty() }
        assertTrue("caption body should be WebVTT, got '${body.take(16)}'", body.startsWith("WEBVTT"))

        val result = extractCueSamples(body.toByteArray(Charsets.UTF_8))

        assertEquals(MimeTypes.APPLICATION_MEDIA3_CUES, result.mimeType)
        assertTrue("cue samples expected, got ${result.sampleCount}", result.sampleCount > 0)
        assertTrue("sample payload must not be empty", result.firstSampleSize > 0)
    }
}

private class CueExtractionResult(val mimeType: String?, val sampleCount: Int, val firstSampleSize: Int)

// Runs a WebVTT payload through Media3's SubtitleExtractor exactly like
// IndioMediaSourceFactory attaches caption sources to the player, and reports
// what the text renderer would receive.
private fun extractCueSamples(webVtt: ByteArray): CueExtractionResult {
    val format = Format.Builder()
        .setSampleMimeType(MimeTypes.TEXT_VTT)
        .setLanguage("en")
        .setSelectionFlags(C.SELECTION_FLAG_DEFAULT)
        .build()

    val parserFactory = DefaultSubtitleParserFactory()
    if (!parserFactory.supportsFormat(format)) return CueExtractionResult(null, 0, 0)

    val extractor = SubtitleExtractor(parserFactory.create(format), format)
    val input = FakeExtractorInput.Builder()
        .setData(webVtt)
        .build()
    val output = FakeTrackOutput(false)
    val extractorOutput = object : ExtractorOutput {
        override fun track(id: Int, type: Int): TrackOutput = output
        override fun endTracks() = Unit
        override fun seekMap(seekMap: SeekMap) = Unit
    }
    val positionHolder = PositionHolder()

    extractor.init(extractorOutput)
    var result = extractor.read(input, positionHolder)
    while (result == Extractor.RESULT_CONTINUE) {
        result = extractor.read(input, positionHolder)
    }
    extractor.release()

    val firstSampleSize = if (output.sampleCount > 0) output.getSampleData(0).size else 0
    return CueExtractionResult(output.lastFormat?.sampleMimeType, output.sampleCount, firstSampleSize)
}
