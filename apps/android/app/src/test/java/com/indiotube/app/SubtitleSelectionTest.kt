package com.indiotube.app

import com.indiotube.app.data.SubtitleTrack
import com.indiotube.app.data.VideoQualities
import com.indiotube.app.data.dedupeSubtitles
import com.indiotube.app.data.forLanguage
import com.indiotube.app.data.subtitleVttUrl
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

// YouTube serves captions as srv3 XML, which Media3 cannot parse, so the
// resolver asks for the WebVTT rendition instead. These tests pin that URL
// rewrite, the one-row-per-language rule, and the remembered-language match.
class SubtitleSelectionTest {

    private fun track(tag: String, auto: Boolean = false, label: String = tag) =
        SubtitleTrack(
            languageTag = tag,
            label = label,
            url = "https://example.com/$tag",
            autoGenerated = auto,
        )

    @Test
    fun ttmlUrlsAreRewrittenToVtt() {
        assertEquals(
            "https://www.youtube.com/api/timedtext?v=x&lang=en&fmt=vtt",
            subtitleVttUrl("https://www.youtube.com/api/timedtext?v=x&lang=en&fmt=ttml"),
        )
        assertEquals(
            "https://www.youtube.com/api/timedtext?v=x&lang=en&fmt=vtt&x=1",
            subtitleVttUrl("https://www.youtube.com/api/timedtext?v=x&lang=en&fmt=srv3&x=1"),
        )
        assertEquals(
            "https://www.youtube.com/api/timedtext?fmt=vtt",
            subtitleVttUrl("https://www.youtube.com/api/timedtext?fmt=ttml"),
        )
    }

    @Test
    fun missingFormatIsAppended() {
        assertEquals(
            "https://www.youtube.com/api/timedtext?v=x&lang=en&fmt=vtt",
            subtitleVttUrl("https://www.youtube.com/api/timedtext?v=x&lang=en"),
        )
        assertEquals(
            "https://www.youtube.com/api/timedtext?fmt=vtt",
            subtitleVttUrl("https://www.youtube.com/api/timedtext"),
        )
    }

    @Test
    fun manualTrackWinsOverAutoForTheSameLanguage() {
        val tracks = listOf(
            track("en", auto = true, label = "English (auto-generated)"),
            track("en", auto = false, label = "English"),
            track("de-DE", auto = false, label = "German (Germany)"),
        ).dedupeSubtitles()

        assertEquals(2, tracks.size)
        assertEquals("English", tracks.first { it.languageTag == "en" }.label)
        assertTrue(tracks.none { it.autoGenerated && it.languageTag == "en" })
    }

    @Test
    fun autoGeneratedTrackSurvivesWhenThereIsNoManualOne() {
        val tracks = listOf(track("ko", auto = true, label = "Korean (auto-generated)"))
            .dedupeSubtitles()
        assertEquals(1, tracks.size)
        assertTrue(tracks.single().autoGenerated)
    }

    @Test
    fun rememberedLanguageMatchesExactTagFirst() {
        val tracks = listOf(track("en-GB"), track("en-US"), track("es-419"))
        assertEquals("en-US", tracks.forLanguage("en-US")?.languageTag)
        assertEquals("en-GB", tracks.forLanguage("EN-gb")?.languageTag)
    }

    @Test
    fun rememberedLanguageFallsBackToPrimarySubtag() {
        val tracks = listOf(track("de-DE"), track("es-419"))
        assertEquals("de-DE", tracks.forLanguage("de")?.languageTag)
        assertEquals("es-419", tracks.forLanguage("es")?.languageTag)
        assertNull(tracks.forLanguage("en"))
    }

    @Test
    fun blankOrMissingPreferenceSelectsNothing() {
        val tracks = listOf(track("en"))
        assertNull(tracks.forLanguage(null))
        assertNull(tracks.forLanguage(""))
        assertNull(tracks.forLanguage("   "))
    }

    @Test
    fun captionlessVideoHasEmptyTrackList() {
        val qualities = VideoQualities(options = emptyList(), auto = null, audio = null)
        assertTrue(qualities.subtitles.isEmpty())
    }
}
