// Ad-free video URLs via NewPipeExtractor - the same extractor the NewPipe app
// uses. Progressive (non-segmented) streams only:
//  - muxed: video+audio in one file, plays directly and saves offline as a
//    single playable file
//  - video-only + audio: paired by the player (MergingMediaSource) to offer
//    the higher resolutions YouTube only serves separately
data class ResolvedStream(
    val url: String,
    val ext: String,
    val mime: String?,
    val height: Int,
    val codec: String? = null,
) {
    val isVideo: Boolean get() = mime?.startsWith("video/") == true
    val isAudio: Boolean get() = mime?.startsWith("audio/") == true

    val videoDownloadMuxable: Boolean get() =
        mime?.contains("mp4") == true && codec?.startsWith("avc") == true

    val audioDownloadMuxable: Boolean get() = mime?.contains("mp4") == true
}

// One selectable caption track. YouTube's timedtext endpoint returns srv3
// ("ttml") by default, which Media3 cannot parse, so the URL is rewritten to
// the WebVTT variant - the same captions in a format every player understands.
data class SubtitleTrack(
    val languageTag: String,
    val label: String,
    val url: String,
    val mime: String = "text/vtt",
    val autoGenerated: Boolean = false,
)

// Ask YouTube's timedtext endpoint for the WebVTT rendition, keeping every
// other (signed) query parameter untouched.
fun subtitleVttUrl(url: String): String {
    val fmt = Regex("([?&])fmt=[^&]*")
    return when {
        fmt.containsMatchIn(url) -> fmt.replace(url) { m -> m.groupValues[1] + "fmt=vtt" }
        url.contains('?') -> "$url&fmt=vtt"
        else -> "$url?fmt=vtt"
    }
}

// YouTube offers manual and auto-generated captions for the same language.
// The manual one wins (YouTube hides the auto one in that case), and the menu
// gets exactly one row per language.
fun List<SubtitleTrack>.dedupeSubtitles(): List<SubtitleTrack> {
    val out = LinkedHashMap<String, SubtitleTrack>()
    for (track in this) {
        val key = track.languageTag.lowercase()
        val existing = out[key]
        if (existing == null || (existing.autoGenerated && !track.autoGenerated)) {
            out[key] = track
        }
    }
    return out.values.toList()
}

// The remembered caption language applied to a video's ladder. An exact tag
// match wins, then the primary subtag ("en" matches "en-GB" and vice versa).
fun List<SubtitleTrack>.forLanguage(tag: String?): SubtitleTrack? {
    val wanted = tag?.trim()?.lowercase()?.takeIf { it.isNotEmpty() } ?: return null
    return firstOrNull { it.languageTag.lowercase() == wanted }
        ?: firstOrNull {
            it.languageTag.substringBefore('-').lowercase() == wanted.substringBefore('-')
        }
}

// One selectable quality. A height is either backed by a muxed file (single,
// simplest) or by a video-only file that gets paired with the best audio.
data class QualityOption(
    val height: Int,
    val label: String,
    val fps: Int,
    val muxed: ResolvedStream?,
    val videoOnly: ResolvedStream?,
) {
    val hasStream: Boolean get() = muxed != null || videoOnly != null
}

data class VideoQualities(
    val options: List<QualityOption>, // highest first
    val auto: ResolvedStream?,        // best muxed file: what plain "Auto" plays
    val audio: ResolvedStream?,       // best audio-only pair for video-only streams
    val subtitles: List<SubtitleTrack> = emptyList(),
) {
    val bestHeight: Int get() = auto?.height ?: options.firstOrNull()?.height ?: 0

    // Highest quality at or below the requested height, else the lowest
    // available one, so a stale preference never leaves playback without a
    // source.
    fun nearest(height: Int): QualityOption? =
        options.filter { it.height <= height }.maxByOrNull { it.height }
            ?: options.minByOrNull { it.height }

    fun labelFor(height: Int?): String? =
        if (height == null) null else options.firstOrNull { it.height == height }?.label

    // The rung directly below the given height (used when a quality turns out
    // to be unplayable on this device: drop one step instead of giving up).
    fun below(height: Int): QualityOption? =
        options.filter { it.height < height }.maxByOrNull { it.height }

    fun muxedAt(height: Int): ResolvedStream? =
        options.filter { it.muxed != null && it.height <= height }
            .maxByOrNull { it.height }?.muxed
            ?: options.filter { it.muxed != null }.minByOrNull { it.height }?.muxed

    fun videoAt(height: Int): ResolvedStream? =
        options.filter { it.videoOnly != null && it.height <= height }
            .maxByOrNull { it.height }?.videoOnly
            ?: options.filter { it.videoOnly != null }.minByOrNull { it.height }?.videoOnly

    fun downloadOptions(): List<QualityOption> = options.filter { option ->
        option.muxed != null || (
            audio?.audioDownloadMuxable == true &&
                option.videoOnly?.videoDownloadMuxable == true
            )
    }
}

data class DownloadSources(
    val video: ResolvedStream,
    val audio: ResolvedStream?,
)

internal fun downloadSources(qualities: VideoQualities, height: Int?): DownloadSources {
    if (height == null) {
        qualities.auto?.let { return DownloadSources(it, null) }
        val best = qualities.downloadOptions().firstOrNull()
        best?.muxed?.let { return DownloadSources(it, null) }
        val audio = qualities.audio
        if (best?.videoOnly != null && audio?.audioDownloadMuxable == true) {
            return DownloadSources(best.videoOnly, audio)
        }
        throw IOException("This video has no downloadable stream without ads")
    }

    val option = qualities.nearest(height)
    if (option != null) {
        option.muxed?.let { return DownloadSources(it, null) }
        val video = option.videoOnly
        val audio = qualities.audio
        if (video?.videoDownloadMuxable == true && audio?.audioDownloadMuxable == true) {
            return DownloadSources(video, audio)
        }
    }

    val fallback = qualities.options
        .filter { it.muxed != null && it.height <= height }
        .maxByOrNull { it.height }?.muxed
        ?: qualities.auto
    return DownloadSources(
        fallback ?: throw IOException("This quality isn't available for download"),
        null,
    )
}

// The exact streams a quality selection will open. Used to warm only the CDN
// connections that the player is about to use, never an unused sibling file.
internal fun QualityOption.playbackStreams(audio: ResolvedStream?): List<ResolvedStream> {
    muxed?.let { return listOf(it) }
    val video = videoOnly ?: return emptyList()
    return listOfNotNull(video, audio)
}

internal fun playbackWarmStreams(
    qualities: VideoQualities,
    height: Int?,
): List<ResolvedStream> {
    if (height == null) return listOfNotNull(qualities.auto)
    val option = qualities.nearest(height) ?: return emptyList()
    return option.playbackStreams(qualities.audio)
}

// True when the rung a default-quality preference resolves to is exactly the
// stream plain Auto already plays (the best single file). A video that offers
// nothing better than Auto is then already starting on the right stream, and
// swapping would only rebuild the same source for no visible change.
internal fun VideoQualities.playsAutoStream(height: Int?): Boolean {
    if (height == null) return true
    val best = auto ?: return true
    val rung = nearest(height) ?: return true
    return rung.height == best.height && rung.muxed != null
}

// The player URIs a quality selection maps to. Pure strings on purpose so the
// mapping is unit-testable without Android:
//   auto            -> indio://stream/{id}                (best muxed file)
//   muxed quality   -> indio://stream/{id}?type=muxed&h=N  (one file)
//   merged quality  -> indio://merge/{id}?h=N              (video + audio)
object QualityUris {
    fun auto(videoId: String): String = "indio://stream/$videoId"

    fun muxed(videoId: String, height: Int): String =
        "indio://stream/$videoId?type=muxed&h=$height"

    fun merged(videoId: String, height: Int): String =
        "indio://merge/$videoId?h=$height"

    // Null means the requested height has no playable source at all, in which
    // case the player must keep what it has instead of switching blindly.
    fun target(videoId: String, height: Int?, qualities: VideoQualities): String? {
        if (height == null) return auto(videoId)
        val option = qualities.nearest(height) ?: return null
        return when {
            option.muxed != null -> muxed(videoId, option.height)
            option.videoOnly != null -> merged(videoId, option.height)
            else -> null
        }
    }
}

class StreamResolver(private val http: OkHttpClient) {

    private data class Entry(val qualities: VideoQualities, val at: Long)

    private val cache = ConcurrentHashMap<String, Entry>()
    private val misses = ConcurrentHashMap<String, Long>()
    private val locks = ConcurrentHashMap<String, Mutex>()

    companion object {
        private const val TTL_MS = 5 * 3600 * 1000L // URLs live ~6h
        private const val MISS_TTL_MS = 60 * 1000L
        @Volatile private var inited = false

        fun init(http: OkHttpClient) {
            if (inited) return
            synchronized(this) {
                if (inited) return
                NewPipe.init(NpDownloader(http))
                inited = true
            }
        }
    }

    // forceRefresh bypasses both cache and negative-cache - used when a
    // download retry needs a fresh URL (expired or rejected by the CDN).
    // A non-null height pins the one-file download to that rung; downloads are
    // always progressive muxed streams, never video-only halves.
    fun resolveBlocking(
        videoId: String,
        height: Int? = null,
        forceRefresh: Boolean = false,
    ): ResolvedStream {
        val qualities = qualities(videoId, forceRefresh)
        if (height != null) {
            qualities.muxedAt(height)?.let { return it }
        }
        return qualities.auto ?: throw IOException("This video has no downloadable stream without ads")
    }

    fun resolveDownloadBlocking(
        videoId: String,
        height: Int? = null,
        forceRefresh: Boolean = false,
    ): DownloadSources = downloadSources(qualities(videoId, forceRefresh), height)

    // Streams behind an explicit quality selection. "video" and "audio" are
    // the two halves the player merges; "muxed" is the one-file variant.
    fun resolveTrackBlocking(videoId: String, kind: String, height: Int): ResolvedStream {
        val qualities = qualities(videoId)
        return when (kind) {
            "audio" -> qualities.audio
                ?: throw IOException("No audio stream was offered for this video")
            "video" -> qualities.videoAt(height)
                ?: throw IOException("This quality isn't available for this video")
            "muxed" -> qualities.muxedAt(height)
                ?: throw IOException("This quality isn't available for this video")
            else -> qualities.auto
                ?: throw IOException("This video has no downloadable stream without ads")
        }
    }

    // Stores a resolved ladder under one definition, so the cache and its
    // timestamp cannot drift apart.
    internal fun cacheQualities(videoId: String, qualities: VideoQualities) {
        cache[videoId] = Entry(qualities, System.currentTimeMillis())
    }

    // The ladder of a video that is already known, without ever waiting on
    // the extractor. The player reads it to start straight on a remembered
    // quality, so this must stay a pure in-memory lookup.
    fun cachedQualities(
        videoId: String,
        now: Long = System.currentTimeMillis(),
    ): VideoQualities? = cache[videoId]?.takeIf { now - it.at < TTL_MS }?.qualities

    fun qualities(videoId: String, forceRefresh: Boolean = false): VideoQualities {
        if (!forceRefresh) {
            cache[videoId]?.let { if (System.currentTimeMillis() - it.at < TTL_MS) return it.qualities }
            misses[videoId]?.let {
                if (System.currentTimeMillis() - it < MISS_TTL_MS) {
                    throw IOException("Video stream unavailable right now")
                }
            }
        }
        // one extraction per video even under concurrent requests
        val mutex = locks.computeIfAbsent(videoId) { Mutex() }
        return runBlocking {
            mutex.withLock {
                if (!forceRefresh) {
                    cache[videoId]?.let {
                        if (System.currentTimeMillis() - it.at < TTL_MS) return@withLock it.qualities
                    }
                }
                try {
                    val qualities = extract(videoId)
                    if (qualities.auto == null && qualities.options.isEmpty()) {
                        throw IOException("This video has no downloadable stream without ads")
                    }
                    cacheQualities(videoId, qualities)
                    misses.remove(videoId)
                    qualities
                } catch (e: Exception) {
                    misses[videoId] = System.currentTimeMillis()
                    throw if (e is IOException) e else IOException(e.message ?: "Couldn't resolve a stream", e)
                }
            }
        }
    }

    private fun extract(videoId: String): VideoQualities {
        val info = StreamInfo.getInfo(NewPipe.getService(0), "https://www.youtube.com/watch?v=$videoId")

        // Some extractor versions return video-only entries in both lists;
        // de-duplicate by URL.
        val allVideo = LinkedHashMap<String, VideoStream>()
        (info.videoStreams + info.videoOnlyStreams).forEach { vs ->
            val url = vs.url
            if (vs.isUrl && url != null && vs.deliveryMethod == DeliveryMethod.PROGRESSIVE_HTTP) {
                allVideo[url] = vs
            }
        }
        val muxed = allVideo.values.filter { !it.isVideoOnly }
        val videoOnly = allVideo.values.filter { it.isVideoOnly }

        val auto = muxed.maxWithOrNull(
            compareBy<VideoStream>({ streamHeight(it) }, { it.bitrate }),
        )?.let { it.toResolved(streamHeight(it)) }

        val audio = bestAudio(info.audioStreams)

        val heights = (muxed.map { streamHeight(it) } + videoOnly.map { streamHeight(it) })
            .filter { it > 0 }
            .distinct()
            .sortedDescending()

        val options = heights.mapNotNull { height ->
            val m = muxed.filter { streamHeight(it) == height }.maxByOrNull { it.bitrate }
            // A video-only track is only useful when there is audio to pair
            // it with; otherwise prefer the muxed variant at this height.
            val v = if (audio != null) {
                videoOnly.filter { streamHeight(it) == height }
                    .minWithOrNull(compareBy<VideoStream>({ codecRank(it) }, { -it.fps }, { -it.bitrate }))
            } else {
                null
            }
            val chosen = v ?: m ?: return@mapNotNull null
            val fps = chosen.fps.takeIf { it > 0 } ?: 0
            QualityOption(
                height = height,
                label = "${height}p" + if (fps >= 50) "$fps" else "",
                fps = fps,
                muxed = m?.toResolved(height),
                videoOnly = v?.toResolved(height),
            )
        }

        return VideoQualities(
            options = options,
            auto = auto,
            audio = audio,
            subtitles = info.subtitles.orEmpty()
                .mapNotNull { it.toTrack() }
                .dedupeSubtitles(),
        )
    }

    private fun SubtitlesStream.toTrack(): SubtitleTrack? {
        val streamUrl = url ?: return null
        if (!isUrl || streamUrl.isBlank()) return null
        val tag = (languageTag ?: locale?.toLanguageTag())
            ?.trim()
            ?.takeIf { it.isNotBlank() }
            ?: "und"
        val name = displayLanguageName?.trim()?.takeIf { it.isNotBlank() } ?: tag
        return SubtitleTrack(
            languageTag = tag,
            label = if (isAutoGenerated) "$name (auto-generated)" else name,
            url = subtitleVttUrl(streamUrl),
            autoGenerated = isAutoGenerated,
        )
    }

    // Prefer AAC/m4a for the widest device support, then the highest bitrate.
    // Only the original audio track is used (not dubs/descriptions).
    private fun bestAudio(all: List<AudioStream>): ResolvedStream? {
        val usable = all.filter { s ->
            val url = s.url
            s.isUrl && url != null && s.deliveryMethod == DeliveryMethod.PROGRESSIVE_HTTP
        }
        val original = usable.filter {
            val t = it.audioTrackType
            t == null || t == AudioTrackType.ORIGINAL
        }
        val pool = original.ifEmpty { usable.filter { it.audioTrackType != AudioTrackType.DESCRIPTIVE } }
        val best = pool.maxWithOrNull(
            compareBy<AudioStream>(
                { audioRank(it) },
                { it.averageBitrate.takeIf { b -> b > 0 } ?: it.bitrate },
            ),
        ) ?: return null
        return best.toResolved()
    }

    private fun streamHeight(v: VideoStream): Int =
        v.height.takeIf { h -> h > 0 }
            ?: v.resolution?.removeSuffix("p")?.toIntOrNull()
            ?: 0

    // H.264 decodes on every Android device; VP9 next; AV1 last.
    private fun codecRank(v: VideoStream): Int = when {
        v.codec?.startsWith("avc") == true -> 0
        v.codec?.startsWith("vp9") == true || v.codec?.startsWith("vp09") == true -> 1
        v.codec?.startsWith("av01") == true -> 2
        else -> 3
    }

    private fun audioRank(s: AudioStream): Int = when {
        s.format == MediaFormat.M4A -> 2
        s.codec?.startsWith("mp4a") == true -> 2
        s.format == MediaFormat.OPUS || s.format == MediaFormat.WEBMA_OPUS -> 1
        s.codec?.startsWith("opus") == true -> 1
        else -> 0
    }

    private fun Stream.toResolved(height: Int = 0): ResolvedStream {
        val streamUrl = url ?: throw IOException("No stream URL was offered for this video")
        val fmt = format
        val mime = fmt?.mimeType
        val ext = fmt?.suffix?.takeIf { it.isNotBlank() } ?: when {
            mime?.contains("mp4") == true -> "mp4"
            mime?.contains("webm") == true -> "webm"
            mime?.contains("3gpp") == true -> "3gp"
            mime?.startsWith("audio/") == true -> "m4a"
            else -> "mp4"
        }
        val codec = when (this) {
            is VideoStream -> codec
            is AudioStream -> codec
            else -> null
        }
        return ResolvedStream(streamUrl, ext, mime, height, codec)
    }
}

private class NpDownloader(private val http: OkHttpClient) : Downloader() {
    override fun execute(request: Request): Response {
        val method = request.httpMethod().uppercase()
        val data = request.dataToSend()
        val body = if (data != null) {
            val ct = request.headers()["Content-Type"]?.firstOrNull()
                ?: request.headers()["content-type"]?.firstOrNull()
                ?: "application/json"
            data.toRequestBody(ct.toMediaTypeOrNull())
        } else null

        val rb = okhttp3.Request.Builder().url(request.url())
        rb.method(method, if (method == "GET" || method == "HEAD") null else (body ?: ByteArray(0).toRequestBody(null)))
        for ((name, values) in request.headers()) {
            when (name.lowercase()) {
                // OkHttp manages these itself; forwarding them breaks gzip
                // transparency and body framing
                "accept-encoding", "content-length", "transfer-encoding", "host", "connection" -> {}
                else -> for (v in values) rb.addHeader(name, v)
            }
        }
        http.newCall(rb.build()).execute().use { r ->
            val text = r.body?.string().orEmpty()
            return Response(r.code, r.message, r.headers.toMultimap(), text, r.request.url.toString())
        }
    }
}
