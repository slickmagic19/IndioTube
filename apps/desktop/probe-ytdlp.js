// Ad-hoc smoke probe: run the real yt-dlp sidecar against a public video and
// push the result through the app's buildQualities mapping. Not part of the
// test suite (needs network + the vendored binary); run with `node probe-ytdlp.js`.
const { spawn } = require('child_process');
const path = require('node:path');
const { buildQualities, subtitleVttUrl } = require('./electron/streams');

const exe = path.join(__dirname, 'vendor', 'ytdlp', 'yt-dlp.exe');
const url = process.argv[2] || 'https://www.youtube.com/watch?v=aqz-KE-bpKQ';

const p = spawn(exe, ['--no-warnings', '--no-playlist', '--dump-single-json', '--skip-download', url], { windowsHide: true });
let out = '';
let err = '';
p.stdout.on('data', (d) => { out += d; });
p.stderr.on('data', (d) => { err += d; });
p.on('error', (e) => { console.error('spawn failed', e.message); process.exit(1); });
p.on('close', (code) => {
  if (code !== 0) { console.error('yt-dlp exit', code, err.slice(-300)); process.exit(1); }
  const info = JSON.parse(out.slice(out.indexOf('{')));
  const q = buildQualities(info);
  console.log('title   :', info.title);
  console.log('live    :', q.isLive, '| members-only:', q.membersOnly, '| duration:', q.durationSec);
  console.log('options :', q.options.map((o) => o.label + (o.videoOnly ? '*' : '')).join(', ') || '(none)');
  console.log('auto    :', q.auto ? q.auto.height + 'p' : '(none)', '| audio pair:', q.audio ? q.audio.codec : 'none');
  console.log('subs    :', q.subtitles.slice(0, 6).map((s) => `${s.languageTag}${s.autoGenerated ? '*' : ''}`).join(', '), `(${q.subtitles.length} total)`);
  const first = q.subtitles[0];
  if (first) console.log('sub url :', subtitleVttUrl(first.url).slice(0, 120));
  if (!q.options.length && !q.isLive) {
    console.error('FAIL: no playable formats — the player would have nothing to play');
    process.exit(2);
  }
  // Sanity: every option must have at least one playable track pair.
  for (const o of q.options) {
    if (!o.muxed && !o.videoOnly) { console.error('FAIL: rung', o.label, 'has no stream'); process.exit(2); }
    if (o.videoOnly && !q.audio) { console.error('FAIL: video-only rung without an audio pair'); process.exit(2); }
  }
  console.log('OK');
});
