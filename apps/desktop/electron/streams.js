// Stream resolution + media proxy + downloads, all through the yt-dlp
// sidecar. This is the desktop counterpart of Android's StreamResolver.kt:
// the extractor differs (yt-dlp instead of NewPipeExtractor), but the shape
// handed to the player is the same - a muxed-only quality ladder with labels
// like "1080p60", an "auto" pick, and one VTT-readable caption per language.
//
// The renderer never talks to a CDN directly: streams.js runs a tiny
// 127.0.0.1 proxy that forwards Range requests with the right headers and
// hands out opaque /v?t=… tokens, which also keeps long signed URLs out of
// the DOM.
const http = require('node:http');
const fs = require('node:fs');
const path = require('node:path');
const { spawn } = require('node:child_process');
const { Readable } = require('node:stream');
const crypto = require('node:crypto');

const CACHE_TTL_MS = 5 * 3600 * 1000; // URLs live ~6h, same as Android
const MISS_TTL_MS = 60 * 1000;
const PROXY_UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64; rv:121.0) Gecko/20100101 Firefox/121.0';

// Ask timedtext for the WebVTT rendition, keeping every other (signed) query
// parameter untouched - the Android app's subtitleVttUrl, byte for byte.
function subtitleVttUrl(url) {
  if (/[?&]fmt=[^&]*/.test(url)) return url.replace(/([?&])fmt=[^&]*/, '$1fmt=vtt');
  if (url.includes('?')) return `${url}&fmt=vtt`;
  return `${url}?fmt=vtt`;
}

// json3 (YouTube's JSON caption format) -> WebVTT. Used when the fmt=vtt
// rewrite is rejected and yt-dlp handed us a json3 URL instead.
function json3ToVtt(text) {
  let doc;
  try { doc = JSON.parse(text); } catch { return null; }
  const events = Array.isArray(doc.events) ? doc.events : [];
  const lines = ['WEBVTT', ''];
  let i = 0;
  for (const ev of events) {
    const segs = Array.isArray(ev.segs) ? ev.segs : (Array.isArray(ev.seg) ? ev.seg : []);
    const txt = segs.map((s) => (s.utf8 || '').replace(/\n/g, ' ')).join('').trim();
    if (!txt) continue;
    const startMs = Number(ev.tStartMs) || 0;
    const durMs = Number(ev.dDurationMs) || 0;
    lines.push(String(i += 1));
    lines.push(`${clock(startMs)} --> ${clock(startMs + durMs)}`);
    lines.push(txt, '');
  }
  return lines.length > 2 ? lines.join('\n') : null;
}

// TTML/srv1 -> VTT, best-effort: only the common <p begin="…" end="…"> form.
function ttmlToVtt(text) {
  const re = /<p\b[^>]*\bbegin="([\d:.]+)"[^>]*\bend="([\d:.]+)"[^>]*>([\s\S]*?)<\/p>/g;
  const lines = ['WEBVTT', ''];
  let m; let i = 0;
  while ((m = re.exec(text))) {
    const txt = m[3].replace(/<br\s*\/?>/gi, '\n').replace(/<[^>]+>/g, '').trim();
    if (!txt) continue;
    i += 1;
    lines.push(String(i));
    lines.push(`${ttmlClock(m[1])} --> ${ttmlClock(m[2])}`);
    lines.push(txt, '');
  }
  return i ? lines.join('\n') : null;
}

function ttmlClock(s) {
  const parts = String(s).split(':');
  return clock(parts.map(Number).reduce((acc, n) => acc * 1000 + n, 0));
}

function clock(ms) {
  const clamped = Math.max(0, Math.round(ms));
  const h = Math.floor(clamped / 3_600_000);
  const m = Math.floor((clamped % 3_600_000) / 60_000);
  const sec = Math.floor((clamped % 60_000) / 1000);
  const milli = clamped % 1000;
  return `${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}:${String(sec).padStart(2, '0')}.${String(milli).padStart(3, '0')}`;
}

// YouTube offers manual and auto-generated captions for the same language.
// The manual one wins and the menu gets exactly one row per language,
// matching Android's dedupeSubtitles().
function dedupeSubtitles(tracks) {
  const out = new Map();
  for (const t of tracks) {
    const key = t.languageTag.toLowerCase();
    const existing = out.get(key);
    if (!existing || (existing.autoGenerated && !t.autoGenerated)) out.set(key, t);
  }
  return [...out.values()];
}

// YouTube's logged-out clients no longer serve muxed files above 360p, so
// the ladder mirrors Android's VideoQualities exactly: every rung is either
// a muxed file (vcodec + acodec together) or a video-only file that the
// player pairs with the best audio-only track (dual <video>/<audio>
// elements in sync). Codec preference mirrors Android: avc decodes
// everywhere, then vp9, then av01.
function codecRank(v) {
  const c = (v.vcodec || '').toLowerCase();
  if (c.startsWith('avc')) return 0;
  if (c.startsWith('vp9') || c.startsWith('vp09')) return 1;
  if (c.startsWith('av01')) return 2;
  return 3;
}

function audioRank(f) {
  const c = (f.acodec || '').toLowerCase();
  if (f.ext === 'm4a' || c.startsWith('mp4a')) return 2;
  if (f.ext === 'weba' || f.ext === 'opus' || c.startsWith('opus')) return 1;
  return 0;
}

function formatHeight(f) {
  if (f.height > 0) return f.height;
  const m = /(\d{3,4})p/.exec(f.format_note || '');
  return m ? Number(m[1]) : 0;
}

// "Auto" means "720p when the video has it", not "whatever the biggest file
// is": 720p is the sweet spot most people watch on a desktop and it keeps
// startup fast. Falls back to the highest rung at or below 720, and for a
// video that only has bigger rungs, the smallest one offered.
const AUTO_HEIGHT_CAP = 720;
function resolveAutoHeight(q, cap = AUTO_HEIGHT_CAP) {
  if (!q || !Array.isArray(q.options) || !q.options.length) return q && q.auto ? q.auto.height : 0;
  const atOrBelow = q.options.filter((o) => o.height <= cap);
  if (atOrBelow.length) return atOrBelow.reduce((a, b) => (b.height > a.height ? b : a)).height;
  return q.options.reduce((a, b) => (b.height < a.height ? b : a)).height;
}

// Map the yt-dlp format list onto the Android-shaped quality ladder.
// Exported pure for tests (no process, no network).
function buildQualities(info) {
  const all = Array.isArray(info.formats) ? info.formats : [];
  const playable = (f) => f.url && f.protocol === 'https' || (f.url && !f.protocol);
  const muxed = all.filter((f) => playable(f) && f.vcodec && f.vcodec !== 'none' && f.acodec && f.acodec !== 'none');
  const videoOnly = all.filter((f) => playable(f) && f.vcodec && f.vcodec !== 'none' && (!f.acodec || f.acodec === 'none') && formatHeight(f) > 0);

  // Best audio-only track: original audio, m4a preferred, then bitrate -
  // Android's bestAudio().
  const audios = all.filter((f) => playable(f) && (!f.vcodec || f.vcodec === 'none') && f.acodec && f.acodec !== 'none');
  const audio = audios.length ? audios.reduce((best, f) => {
    const score = (x) => audioRank(x) * 1e9 + (x.abr || x.tbr || 0);
    return score(f) > score(best) ? f : best;
  }, audios[0]) : null;

  const bestMuxedAt = (h) => muxed.filter((f) => formatHeight(f) === h)
    .sort((a, b) => (b.tbr || 0) - (a.tbr || 0))[0] || null;
  const bestVideoAt = (h) => {
    if (!audio) return null;
    const cands = videoOnly.filter((f) => formatHeight(f) === h);
    if (!cands.length) return null;
    return cands.sort((a, b) =>
      codecRank(a) - codecRank(b)
      || (b.fps || 0) - (a.fps || 0)
      || (b.tbr || 0) - (a.tbr || 0))[0];
  };

  const heights = [...new Set([...muxed.map(formatHeight), ...videoOnly.map(formatHeight)])]
    .filter((h) => h > 0)
    .sort((a, b) => b - a);

  const wrap = (f, h) => f && ({
    height: h,
    url: f.url,
    ext: f.ext || 'mp4',
    codec: f.vcodec || f.acodec || null,
    bitrate: f.tbr || 0,
  });

  const options = heights.map((h) => {
    const m = bestMuxedAt(h);
    const v = bestVideoAt(h);
    const chosen = v || m; // Android prefers the higher rung when audio exists
    const fps = Math.round(chosen.fps || 0);
    return {
      height: h,
      label: `${h}p${fps >= 50 ? fps : ''}`,
      fps,
      muxed: wrap(m, h),
      videoOnly: wrap(v, h),
    };
  });

  // auto = best muxed file (what plain "Auto" plays); when the video has no
  // muxed rung at all, fall to the top split option.
  const bestMuxed = muxed.slice().sort((a, b) => (formatHeight(b) - formatHeight(a)) || ((b.tbr || 0) - (a.tbr || 0)))[0];
  const auto = bestMuxed ? wrap(bestMuxed, formatHeight(bestMuxed)) : (options[0] && (options[0].videoOnly || options[0].muxed)) || null;

  const subs = [];
  const manual = info.subtitles || {};
  const autoCaps = info.automatic_captions || {};
  const pick = (lang, list, autoGenerated) => {
    const url = pickUrl(list);
    if (!url) return;
    subs.push({
      languageTag: lang,
      label: pickName(list) || lang,
      url,
      autoGenerated,
    });
  };
  for (const [lang, list] of Object.entries(manual)) pick(lang, list, false);
  for (const [lang, list] of Object.entries(autoCaps)) pick(lang, list, true);

  const liveStatus = (info.live_status || '').toLowerCase();
  const result = {
    videoId: info.id,
    title: info.title || '',
    durationSec: Math.round(info.duration || 0),
    options,
    auto,
    audio: audio ? { url: audio.url, ext: audio.ext || 'm4a', codec: audio.acodec } : null,
    subtitles: dedupeSubtitles(subs).map((t) => ({ ...t, url: subtitleVttUrl(t.url) })),
    isLive: liveStatus === 'is_live' || liveStatus === 'was_live' || Boolean(info.is_live),
    membersOnly: liveStatus === 'needs_auth',
    error: info.playable_in_status === false ? 'unplayable' : null,
  };
  // What plain "Auto" will actually play (720p when the video offers it).
  result.autoHeight = resolveAutoHeight(result);
  return result;
}

function pickUrl(list) {
  const arr = (list || []).slice().reverse(); // yt-dlp lists lowest first
  const vtt = arr.find((x) => x.ext === 'vtt' && x.url);
  if (vtt) return vtt.url;
  const json3 = arr.find((x) => x.ext === 'json3' && x.url);
  if (json3) return json3.url;
  const ttml = arr.find((x) => (x.ext === 'ttml' || x.ext === 'srv1') && x.url);
  if (ttml) return ttml.url;
  const any = arr.find((x) => x.url);
  return any ? any.url : null;
}

function pickName(list) {
  const first = (list || [])[0];
  if (!first) return null;
  return first.name || first.language_code || null;
}

function createStreams({ ytdlpPath, downloadDir, onDownloadEvent }) {
  const cache = new Map();     // videoId -> { at, qualities }
  const misses = new Map();    // videoId -> at (negative cache)
  const inflight = new Map();  // videoId -> Promise
  const tokens = new Map();    // token -> url
  const downloads = new Map(); // videoId -> { proc, file }
  let server = null;
  let port = 0;
  let hasFfmpeg = null;

  // ---- extraction ------------------------------------------------------------

  function runYtdlp(args, { timeoutMs = 60_000 } = {}) {
    return new Promise((resolve, reject) => {
      const proc = spawn(ytdlpPath, args, { windowsHide: true });
      let out = '';
      let err = '';
      const timer = setTimeout(() => {
        try { proc.kill(); } catch { /* gone */ }
        reject(new Error('stream lookup timed out'));
      }, timeoutMs);
      proc.stdout.on('data', (d) => { out += d; });
      proc.stderr.on('data', (d) => { err += d.slice(-400); });
      proc.on('error', (e) => { clearTimeout(timer); reject(new Error(`yt-dlp failed to start: ${e.message}`)); });
      proc.on('close', (code) => {
        clearTimeout(timer);
        if (code !== 0) return reject(new Error(err.trim() || `yt-dlp exited with ${code}`));
        resolve(out);
      });
    });
  }

  async function ffmpegAvailable() {
    if (hasFfmpeg !== null) return hasFfmpeg;
    hasFfmpeg = await new Promise((resolve) => {
      const proc = spawn('ffmpeg', ['-version'], { windowsHide: true });
      proc.on('error', () => resolve(false));
      proc.on('close', (code) => resolve(code === 0));
      if (proc.stdout) proc.stdout.resume();
      setTimeout(() => { try { proc.kill(); } catch { /* gone */ } resolve(false); }, 5000).unref();
    });
    return hasFfmpeg;
  }

  async function extract(videoId) {
    // The info dict always carries the subtitles/automatic_captions URL
    // tables, so plain metadata dumping is enough - no --write-subs.
    const out = await runYtdlp([
      '--no-warnings', '--no-playlist', '--dump-single-json', '--skip-download',
      `https://www.youtube.com/watch?v=${videoId}`,
    ], { timeoutMs: 90_000 });
    // Some builds print warnings before the JSON; the document starts at the
    // first "{"
    const brace = out.indexOf('{');
    if (brace < 0) throw new Error('yt-dlp returned no metadata');
    let info;
    try { info = JSON.parse(out.slice(brace)); } catch (e) {
      throw new Error(`could not read stream metadata (${e.message})`);
    }
    if (info.errors || (info.description || '').includes('not available')) {
      throw new Error('Video unavailable (private, deleted or region-blocked)');
    }
    return info;
  }

  async function qualities(videoId, force = false) {
    if (!force) {
      const hit = cache.get(videoId);
      if (hit && Date.now() - hit.at < CACHE_TTL_MS) return hit.qualities;
      const miss = misses.get(videoId);
      if (miss && Date.now() - miss < MISS_TTL_MS) {
        throw new Error('Video stream unavailable right now');
      }
    }
    // one extraction per video even under concurrent requests
    const pending = inflight.get(videoId);
    if (pending && !force) return pending;
    const job = (async () => {
      try {
        const info = await extract(videoId);
        const q = buildQualities(info);
        if (!q.options.length && !q.isLive) {
          throw new Error('This video has no downloadable stream without ads');
        }
        cache.set(videoId, { at: Date.now(), qualities: q });
        misses.delete(videoId);
        return q;
      } catch (e) {
        misses.set(videoId, Date.now());
        throw e;
      } finally {
        inflight.delete(videoId);
      }
    })();
    inflight.set(videoId, job);
    return job;
  }

  // Nearest rung at or below the requested height, else the lowest, exactly
  // like Android's VideoQualities.nearest().
  function nearest(q, height) {
    const below = q.options.filter((o) => o.height <= height);
    if (below.length) return below.reduce((a, b) => (b.height > a.height ? b : a));
    return q.options.length ? q.options.reduce((a, b) => (b.height < a.height ? b : a)) : null;
  }

  // The two URLs the player needs for a selection: one file when a muxed
  // rung exists, otherwise the video-only half plus the shared audio.
  function pickTracks(q, height) {
    if (!q.options.length && !q.auto) throw new Error('This video has no ad-free stream');
    const target = height == null ? resolveAutoHeight(q) : height;
    const option = nearest(q, target);
    if (option) {
      if (option.videoOnly) {
        return { video: option.videoOnly.url, audio: q.audio && q.audio.url, height: option.height, label: height == null ? 'Auto' : option.label };
      }
      if (option.muxed) {
        return { video: option.muxed.url, audio: null, height: option.height, label: height == null ? 'Auto' : option.label };
      }
    }
    if (q.auto) return { video: q.auto.url, audio: null, height: q.auto.height, label: 'Auto' };
    throw new Error('This quality isn\'t available for this video');
  }

  function tokenFor(url) {
    const token = crypto.randomBytes(8).toString('hex');
    tokens.set(token, { url, at: Date.now() });
    if (tokens.size > 400) {
      const oldest = [...tokens.entries()].sort((a, b) => a[1].at - b[1].at)[0];
      if (oldest) tokens.delete(oldest[0]);
    }
    return token;
  }

  function proxied(url) {
    return `http://127.0.0.1:${port}/v?t=${tokenFor(url)}`;
  }

  // The player URLs a quality selection maps to - the desktop counterpart of
  // QualityUris.target() on Android, one proxy token per file.
  async function playUrl(videoId, height) {
    const q = await qualities(videoId);
    if (q.isLive) throw new Error('Live videos are not playable on desktop yet');
    const t = pickTracks(q, height);
    return {
      video: proxied(t.video),
      audio: t.audio ? proxied(t.audio) : null,
      height: t.height,
      label: t.label,
    };
  }

  async function subtitleUrl(videoId, lang) {
    const q = await qualities(videoId);
    const wanted = (lang || '').toLowerCase();
    let t = q.subtitles.find((x) => x.languageTag.toLowerCase() === wanted);
    if (!t && wanted) {
      t = q.subtitles.find((x) => x.languageTag.toLowerCase().split('-')[0] === wanted.split('-')[0]);
    }
    if (!t) return null;
    return `http://127.0.0.1:${port}/subs?t=${tokenFor(t.url)}&ext=1`;
  }

  // ---- proxy -------------------------------------------------------------------

  // Small LRU of exact range responses. Scrubbing asks for the same byte
  // windows repeatedly (audio especially), and re-fetching them from the CDN
  // is what makes a seek feel like a stutter: served from memory it is
  // instant. Total memory is capped, per-entry too (video 200s are huge).
  const mediaCache = new Map();
  const CACHE_MAX_BYTES = 48 * 1024 * 1024;
  const CACHE_MAX_ENTRY = 12 * 1024 * 1024;
  let cacheBytes = 0;

  function cacheGet(key) {
    const hit = mediaCache.get(key);
    if (!hit) return null;
    mediaCache.delete(key); // refresh LRU position
    mediaCache.set(key, hit);
    return hit;
  }

  function cacheSet(key, entry) {
    if (entry.body.length > CACHE_MAX_ENTRY) return;
    const prev = mediaCache.get(key);
    if (prev) cacheBytes -= prev.body.length;
    mediaCache.set(key, entry);
    cacheBytes += entry.body.length;
    while (cacheBytes > CACHE_MAX_BYTES && mediaCache.size > 1) {
      const oldest = mediaCache.keys().next().value;
      const gone = mediaCache.get(oldest);
      mediaCache.delete(oldest);
      cacheBytes -= gone ? gone.body.length : 0;
    }
  }

  function corsHeaders() {
    // The renderer runs on the vite/dev-server origin; the proxy is a
    // different port, so range responses must be CORS-readable.
    return { 'access-control-allow-origin': '*', 'access-control-allow-headers': 'range' };
  }

  function sendFileRange(req, res, filePath) {
    fs.stat(filePath, (err, stat) => {
      if (res.destroyed || res.writableEnded) return;
      if (err || !stat.isFile()) {
        try { res.writeHead(404); res.end('missing'); } catch { /* gone */ }
        return;
      }
      const range = /bytes=(\d*)-(\d*)/.exec(req.headers.range || '');
      if (!range) {
        res.writeHead(200, {
          ...corsHeaders(),
          'content-type': contentTypeFor(filePath),
          'content-length': stat.size,
          'accept-ranges': 'bytes',
        });
        return fs.createReadStream(filePath)
          .on('error', () => { try { res.destroy(); } catch { /* gone */ } })
          .pipe(res);
      }
      let start = Number(range[1]);
      let end = range[2] ? Number(range[2]) : stat.size - 1;
      if (!Number.isFinite(start) || start < 0 || start >= stat.size) start = 0;
      if (end >= stat.size) end = stat.size - 1;
      if (end < start) { res.writeHead(416, { 'content-range': `bytes */${stat.size}` }); return res.end(); }
      res.writeHead(206, {
        ...corsHeaders(),
        'content-type': contentTypeFor(filePath),
        'content-length': end - start + 1,
        'content-range': `bytes ${start}-${end}/${stat.size}`,
        'accept-ranges': 'bytes',
      });
      fs.createReadStream(filePath, { start, end })
        .on('error', () => { try { res.destroy(); } catch { /* gone */ } })
        .pipe(res);
    });
  }

  function contentTypeFor(file) {
    const ext = path.extname(file).toLowerCase();
    if (ext === '.mp4') return 'video/mp4';
    if (ext === '.webm') return 'video/webm';
    if (ext === '.mkv') return 'video/x-matroska';
    if (ext === '.m4a') return 'audio/mp4';
    return 'application/octet-stream';
  }

  // A seek aborts the in-flight range request; without these guards the
  // resulting 'terminated' fetch rejection surfaced as an Electron main
  // process crash dialog. Every branch now fails soft and cleans up sockets.
  function guardStreams(req, res) {
    req.on('error', () => { /* client went away */ });
    res.on('error', () => { /* response already closed */ });
    res.on('close', () => { /* nothing to flush */ });
  }

  async function proxyStream(url, req, res) {
    const headers = { 'user-agent': PROXY_UA, referer: 'https://www.youtube.com/' };
    if (req.headers.range) headers.range = req.headers.range;
    const key = `${url}|${req.headers.range || ''}`;
    const cached = cacheGet(key);
    if (cached) {
      res.writeHead(cached.status, {
        ...corsHeaders(),
        'content-type': cached.contentType,
        'accept-ranges': 'bytes',
        'content-length': cached.body.length,
        ...(cached.contentRange ? { 'content-range': cached.contentRange } : {}),
      });
      res.end(cached.body);
      return;
    }
    // Cancel the upstream fetch when the player abandons this range.
    const ac = new AbortController();
    req.on('close', () => { try { ac.abort(); } catch { /* gone */ } });
    try {
      const up = await fetch(url, { headers, signal: ac.signal });
      if (res.destroyed || res.writableEnded) { try { ac.abort(); } catch { /* gone */ } return; }
      const contentType = up.headers.get('content-type') || 'video/mp4';
      const contentRange = up.headers.get('content-range');
      res.writeHead(up.status, {
        ...corsHeaders(),
        'content-type': contentType,
        'accept-ranges': 'bytes',
        ...(contentRange ? { 'content-range': contentRange } : {}),
        ...(up.headers.get('content-length') ? { 'content-length': up.headers.get('content-length') } : {}),
      });
      if (!up.body) { res.end(); return; }
      const body = Readable.fromWeb(up.body);
      const chunks = [];
      let bytes = 0;
      body.on('data', (chunk) => {
        if (bytes <= CACHE_MAX_ENTRY) { chunks.push(chunk); bytes += chunk.length; }
      });
      body.on('end', () => {
        if (ac.signal.aborted || bytes === 0 || bytes > CACHE_MAX_ENTRY) return;
        if (up.status !== 200 && up.status !== 206) return;
        cacheSet(key, {
          status: up.status,
          contentType,
          contentRange: contentRange || undefined,
          body: Buffer.concat(chunks),
        });
      });
      body.on('error', () => { try { res.destroy(); } catch { /* gone */ } });
      res.on('close', () => { try { body.destroy(); } catch { /* gone */ } });
      body.pipe(res);
    } catch (e) {
      if (ac.signal.aborted || e?.name === 'AbortError') return; // a normal seek
      if (!res.destroyed && !res.headersSent) {
        res.writeHead(502, { 'content-type': 'text/plain' });
        res.end(`proxy error: ${e.message}`);
      } else {
        try { res.destroy(); } catch { /* gone */ }
      }
    }
  }

  async function serveSubtitle(t, req, res) {
    const entry = tokens.get(t);
    if (!entry) { res.writeHead(404); return res.end(); }
    const ac = new AbortController();
    req.on('close', () => { try { ac.abort(); } catch { /* gone */ } });
    try {
      const up = await fetch(entry.url, {
        headers: { 'user-agent': PROXY_UA, referer: 'https://www.youtube.com/' },
        signal: ac.signal,
      });
      if (!up.ok) throw new Error(`HTTP ${up.status}`);
      const text = await up.text();
      let vtt = null;
      if (text.startsWith('WEBVTT')) vtt = text;
      else if (text.trimStart().startsWith('{')) vtt = json3ToVtt(text);
      else if (text.includes('</ttd:p>') || text.includes('</p>')) vtt = ttmlToVtt(text);
      if (!vtt) {
        // fmt=vtt was refused or the conversion found nothing - a stale token
        // is fine to fail soft here; the player just shows no captions.
        throw new Error('unrecognized caption payload');
      }
      if (res.destroyed || res.writableEnded) return;
      res.writeHead(200, { ...corsHeaders(), 'content-type': 'text/vtt; charset=utf-8', 'cache-control': 'no-store' });
      res.end(vtt);
    } catch (e) {
      if (ac.signal.aborted || e?.name === 'AbortError') return;
      try {
        if (!res.destroyed && !res.headersSent) { res.writeHead(502, { 'content-type': 'text/plain' }); res.end('subtitle unavailable'); }
      } catch { /* gone */ }
    }
  }

  async function startProxy() {
    if (server) return;
    server = http.createServer((req, res) => {
      guardStreams(req, res);
      const url = new URL(req.url, 'http://proxy.local');
      if (url.pathname === '/v') {
        const entry = tokens.get(url.searchParams.get('t') || '');
        if (!entry) { res.writeHead(404); return res.end('stale token'); }
        proxyStream(entry.url, req, res).catch(() => { try { res.destroy(); } catch { /* gone */ } });
        return;
      }
      if (url.pathname === '/subs') {
        serveSubtitle(url.searchParams.get('t') || '', req, res)
          .catch(() => { try { res.destroy(); } catch { /* gone */ } });
        return;
      }
      if (url.pathname === '/file') {
        const p = url.searchParams.get('p') || '';
        const resolved = path.resolve(p);
        const root = path.resolve(downloadDir);
        // Downloads only: refuse anything outside the folder.
        if (!resolved.toLowerCase().startsWith(root.toLowerCase())) {
          res.writeHead(403); return res.end('forbidden');
        }
        return sendFileRange(req, res, resolved);
      }
      res.writeHead(404);
      res.end();
    });
    await new Promise((resolve) => server.listen(0, '127.0.0.1', () => {
      port = server.address().port;
      resolve();
    }));
  }

  // ---- downloads ---------------------------------------------------------------

  function downloadFileName(info, out) {
    const m = /\[download\] Destination: (.+)$|(\S+\.(mp4|webm|mkv|m4a)) saved/m.exec(out || '');
    if (m) return (m[1] || m[2] || '').trim();
    return '';
  }

  async function startDownload(video, height) {
    const videoId = video.videoId;
    if (downloads.has(videoId)) return { started: false, reason: 'already downloading' };
    const ffmpeg = await ffmpegAvailable();
    const h = height && height > 0 ? height : 1080;
    const fmt = ffmpeg ? `bv*[height<=${h}]+ba/b[height<=${h}]` : `b[height<=${h}]/b`;
    const outTpl = path.join(downloadDir, '%(title)s [%(id)s].%(ext)s');
    const args = [
      '--no-warnings', '--no-playlist', '--newline', '--progress',
      '-f', fmt,
    ];
    if (ffmpeg) args.push('--merge-output-format', 'mp4');
    args.push('-o', outTpl, `https://www.youtube.com/watch?v=${videoId}`);

    const proc = spawn(ytdlpPath, args, { windowsHide: true });
    const entry = { proc, file: '', totalBytes: 0, receivedBytes: 0 };
    downloads.set(videoId, entry);
    const emit = (patch) => {
      if (onDownloadEvent) onDownloadEvent({ videoId, ...patch });
    };
    emit({ status: 'started', height: h });

    let buf = '';
    proc.stdout.on('data', (d) => {
      buf += d.toString();
      let nl;
      while ((nl = buf.indexOf('\n')) >= 0) {
        const line = buf.slice(0, nl).trim();
        buf = buf.slice(nl + 1);
        if (!line) continue;
        const pct = /\[download\]\s+(\d+(?:\.\d+)?)%/.exec(line);
        const total = /of\s+~?([\d.]+)([KMGT]i?)B/i.exec(line);
        if (total) {
          const mult = { k: 1024, m: 1024 ** 2, g: 1024 ** 3, t: 1024 ** 4 }[total[2][0].toLowerCase()] || 1;
          entry.totalBytes = Math.round(parseFloat(total[1]) * mult);
        }
        if (pct && entry.totalBytes) {
          entry.receivedBytes = Math.round((parseFloat(pct[1]) / 100) * entry.totalBytes);
          emit({ status: 'progress', percent: parseFloat(pct[1]), receivedBytes: entry.receivedBytes, totalBytes: entry.totalBytes });
        } else if (pct) {
          emit({ status: 'progress', percent: parseFloat(pct[1]) });
        }
        const dest = /\[download\] Destination: (.+)$/.exec(line);
        if (dest) entry.file = dest[1].trim();
        if (line.includes('has already been downloaded')) {
          const m = /Destination: (.+)$/.exec(line);
          if (m) entry.file = m[1].trim();
        }
        const merged = /\[Merger\] Merging files into (.+)$/.exec(line);
        if (merged) entry.file = merged[1].trim();
      }
    });
    proc.stderr.on('data', () => { /* yt-dlp progress noise; failures land in close */ });
    proc.on('error', (e) => {
      downloads.delete(videoId);
      emit({ status: 'error', error: `yt-dlp failed to start: ${e.message}` });
    });
    proc.on('close', (code) => {
      downloads.delete(videoId);
      if (code === 0 && entry.file && fs.existsSync(entry.file)) {
        let bytes = 0;
        try { bytes = fs.statSync(entry.file).size; } catch { /* fine */ }
        emit({ status: 'done', file: entry.file, bytes, height: h });
      } else if (code === 0) {
        emit({ status: 'error', error: 'Download finished but the file was not found', height: h });
      } else {
        emit({ status: 'error', error: `Download failed (yt-dlp exit ${code})`, height: h });
      }
    });
    return { started: true };
  }

  function cancelDownload(videoId) {
    const d = downloads.get(videoId);
    if (!d) return false;
    try { d.proc.kill(); } catch { /* gone */ }
    downloads.delete(videoId);
    if (onDownloadEvent) onDownloadEvent({ videoId, status: 'cancelled' });
    return true;
  }

  function localFileUrl(file) {
    return `http://127.0.0.1:${port}/file?p=${encodeURIComponent(file)}`;
  }

  return {
    startProxy,
    get port() { return port; },
    qualities,
    playUrl,
    subtitleUrl,
    localFileUrl,
    startDownload,
    cancelDownload,
    ffmpegAvailable,
    _cache: cache,
  };
}

