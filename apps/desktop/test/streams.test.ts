// yt-dlp mapping + caption helpers — the desktop counterpart of Android's
// QualitySelection tests: muxed-only ladders, avc-first codec preference,
// labels like "1080p60", and VTT rewrites.
import { describe, expect, it } from 'vitest';
import streams from '../electron/streams';

const { buildQualities, subtitleVttUrl, json3ToVtt, dedupeSubtitles, nearest, resolveAutoHeight } = streams as any;

const fmt = (over: any) => ({
  format_id: `f${Math.random().toString(36).slice(2, 7)}`,
  ext: 'mp4',
  vcodec: 'avc1.4d401f',
  acodec: 'mp4a.40.2',
  tbr: 1000,
  fps: 30,
  url: 'https://cdn.example/vid.mp4?sig=x',
  ...over,
});

describe('buildQualities', () => {
  it('builds a muxed + videoOnly ladder with a paired audio track', () => {
    const q = buildQualities({
      id: 'vid1',
      duration: 100,
      formats: [
        fmt({ height: 360, tbr: 600 }),                                        // muxed
        fmt({ height: 1080, vcodec: 'avc1.640028', acodec: 'none', tbr: 4000 }),  // video-only
        fmt({ height: 720, vcodec: 'vp9', acodec: 'none', tbr: 2500 }),            // video-only
        fmt({ height: 2160, vcodec: 'vp9.0', acodec: 'none', tbr: 9000 }),         // video-only 4K
        fmt({ height: 0, vcodec: 'none', acodec: 'opus', ext: 'webm', abr: 160 }), // audio-only
        fmt({ height: 0, vcodec: 'none', acodec: 'mp4a.40.2', ext: 'm4a', abr: 130 }), // audio-only best
        fmt({ height: 1440, vcodec: 'avc1', acodec: 'none', protocol: 'm3u8_n' }),     // HLS: dropped
      ],
    });
    expect(q.options.map((o: any) => o.height)).toEqual([2160, 1440, 1080, 720, 360].filter((h) => q.options.some((o: any) => o.height === h)));
    const top = q.options.find((o: any) => o.height === 2160);
    expect(top.videoOnly).toBeTruthy();
    expect(top.muxed).toBe(null);
    expect(q.auto.url).toBeTruthy();  // the 360p muxed file
    expect(q.auto.height).toBe(360);
    expect(q.audio.codec).toBe('mp4a.40.2'); // m4a preferred over opus
    expect(q.durationSec).toBe(100);
  });

  it('labels 60fps rungs like Android does', () => {
    const q = buildQualities({
      id: 'v', duration: 1,
      formats: [
        fmt({ height: 1080, fps: 60, acodec: 'none' }),
        fmt({ height: 720, fps: 30, acodec: 'none' }),
        fmt({ height: 0, vcodec: 'none', acodec: 'mp4a.40.2', ext: 'm4a' }),
      ],
    });
    expect(q.options[0].label).toBe('1080p60');
    expect(q.options[1].label).toBe('720p');
  });

  it('derives height from format_note when the entry lacks one', () => {
    const q = buildQualities({
      id: 'v', duration: 1,
      formats: [fmt({ height: 0, format_note: '1080p' })],
    });
    expect(q.options[0].height).toBe(1080);
  });

  it('flags live videos', () => {
    const q = buildQualities({ id: 'v', duration: 0, live_status: 'is_live', formats: [] });
    expect(q.isLive).toBe(true);
  });

  it('exposes one caption track per language, manual first', () => {
    const q = buildQualities({
      id: 'v', duration: 1,
      formats: [fmt({ height: 480 })],
      subtitles: { en: [{ ext: 'vtt', url: 'https://video.google.com/timedtext?lang=en&fmt=ttml', name: 'English' }] },
      automatic_captions: {
        en: [{ ext: 'vtt', url: 'https://video.google.com/timedtext?lang=en&kind=asr&fmt=json3', name: 'English (auto)' }],
        es: [{ ext: 'vtt', url: 'https://video.google.com/timedtext?lang=es&fmt=srv3', name: 'Spanish' }],
      },
    });
    const langs = q.subtitles.map((s: any) => s.languageTag);
    expect(langs).toEqual(['en', 'es']);
    const en = q.subtitles.find((s: any) => s.languageTag === 'en');
    expect(en.autoGenerated).toBe(false);
    expect(en.url).toContain('fmt=vtt'); // rewritten from ttml
  });

  it('nearest picks at-or-below, falling back to the lowest rung', () => {
    const q = buildQualities({
      id: 'v', duration: 1,
      formats: [fmt({ height: 1080 }), fmt({ height: 480 }), fmt({ height: 720 })],
    });
    expect(nearest(q, 1080).height).toBe(1080);
    expect(nearest(q, 1440).height).toBe(1080);
    expect(nearest(q, 1000).height).toBe(720);
    expect(nearest(q, 200).height).toBe(480); // lowest available beats "none"
  });

  it('prefers the video+audio pair over the muxed rung, like Android', () => {
    const q = buildQualities({
      id: 'v', duration: 1,
      formats: [
        fmt({ height: 1080, acodec: 'none', vcodec: 'avc1', tbr: 4000 }),
        fmt({ height: 1080, vcodec: 'avc1', acodec: 'mp4a', tbr: 1000 }), // low-bitrate muxed
        fmt({ height: 0, vcodec: 'none', acodec: 'mp4a.40.2', ext: 'm4a' }),
      ],
    });
    const opt = q.options.find((o: any) => o.height === 1080);
    expect(opt.videoOnly).toBeTruthy();
    expect(opt.muxed).toBeTruthy();
  });
});

describe('Auto quality (720p when available)', () => {
  const ladder = (heights: number[]) => ({
    options: heights.map((h) => ({ height: h, label: `${h}p` })),
    auto: null,
  });

  it('picks 720 even when 4K is available', () => {
    expect(resolveAutoHeight(ladder([2160, 1440, 1080, 720, 480, 360]))).toBe(720);
  });

  it('falls back to the highest rung below 720', () => {
    expect(resolveAutoHeight(ladder([1080, 480, 360]))).toBe(480);
    expect(resolveAutoHeight(ladder([2160, 1440]))).toBe(1440); // nothing small offered
    expect(resolveAutoHeight(ladder([1080]))).toBe(1080);
  });

  it('is exposed on the parsed ladder', () => {
    const q = buildQualities({
      id: 'v', duration: 1,
      formats: [
        fmt({ height: 2160, acodec: 'none' }),
        fmt({ height: 1080, acodec: 'none' }),
        fmt({ height: 720, acodec: 'none' }),
        fmt({ height: 360, acodec: 'none' }),
        fmt({ height: 0, vcodec: 'none', acodec: 'mp4a.40.2', ext: 'm4a' }),
      ],
    });
    expect(q.autoHeight).toBe(720);
  });
});

describe('captions', () => {
  it('rewrites fmt without touching other params', () => {
    expect(subtitleVttUrl('https://x/y?lang=en&fmt=srv3&a=1')).toBe('https://x/y?lang=en&fmt=vtt&a=1');
    expect(subtitleVttUrl('https://x/y?lang=en')).toBe('https://x/y?lang=en&fmt=vtt');
    expect(subtitleVttUrl('https://x/y')).toBe('https://x/y?fmt=vtt');
  });

  it('converts json3 payloads to WebVTT', () => {
    const json3 = JSON.stringify({
      events: [
        { tStartMs: 1000, dDurationMs: 2500, segs: [{ utf8: 'Hello ' }, { utf8: 'world' }] },
        { tStartMs: 5000, dDurationMs: 1000, segs: [{ utf8: 'Second line\nwrapped' }] },
        { tStartMs: 0, dDurationMs: 0, segs: [{ utf8: '' }] }, // empty events drop
      ],
    });
    const vtt = json3ToVtt(json3);
    expect(vtt.startsWith('WEBVTT')).toBe(true);
    expect(vtt).toContain('00:00:01.000 --> 00:00:03.500');
    expect(vtt).toContain('Hello world');
    expect(vtt).toContain('Second line wrapped');
    expect((vtt.match(/^\d+$/gm) || []).length).toBe(2);
    expect(json3ToVtt('not json')).toBe(null);
  });

  it('dedupes auto vs manual per language (case-insensitive tag)', () => {
    const out = dedupeSubtitles([
      { languageTag: 'EN', label: 'English (auto)', autoGenerated: true },
      { languageTag: 'en', label: 'English', autoGenerated: false },
      { languageTag: 'fr', label: 'French', autoGenerated: true },
    ]);
    expect(out.length).toBe(2);
    expect(out[0].label).toBe('English');
  });
});
