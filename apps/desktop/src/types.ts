export function formatDuration(seconds: number): string {
  const s = Math.max(0, Math.floor(seconds || 0));
  if (!s) return '';
  const h = Math.floor(s / 3600);
  const m = Math.floor((s % 3600) / 60);
  const sec = s % 60;
  return h > 0
    ? `${h}:${String(m).padStart(2, '0')}:${String(sec).padStart(2, '0')}`
    : `${m}:${String(sec).padStart(2, '0')}`;
}

// "2 days ago" → a rough age in minutes, for merging subscription feeds.
// Port of Models.kt publishAgeMinutes().
export function publishAgeMinutes(publishedText?: string | null): number {
  const t = (publishedText || '').toLowerCase();
  const m = /(\d+)\s*(second|minute|hour|day|week|month|year)/.exec(t);
  if (!m) return Number.MAX_SAFE_INTEGER / 2;
  const value = Number(m[1]);
  switch (m[2]) {
    case 'second': return value / 60;
    case 'minute': return value;
    case 'hour': return value * 60;
    case 'day': return value * 60 * 24;
    case 'week': return value * 60 * 24 * 7;
    case 'month': return value * 60 * 24 * 30;
    case 'year': return value * 60 * 24 * 365;
    default: return Number.MAX_SAFE_INTEGER / 2;
  }
}

export function metaLine(v: VideoItem): string {
  return [v.channelName, v.viewsText, v.publishedText].filter((x) => x && x.trim()).join(' • ');
}

export function watchedFraction(e: HistoryEntry | undefined | null): number | null {
  if (!e || !(e.positionMs > 0)) return null;
  const duration = e.durationMs > 0 ? e.durationMs : (e.video.durationSec || 0) * 1000;
  if (!(duration > 0)) return null;
  return Math.min(1, Math.max(0, e.positionMs / duration));
}
